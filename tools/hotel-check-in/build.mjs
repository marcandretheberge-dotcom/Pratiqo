import path from "node:path";
import fs from "node:fs/promises";
import {fileURLToPath} from "node:url";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {build} from "esbuild";
const require=createRequire(import.meta.url);
const {lines}=require("../../lib/yo/scenarios/checkIn.ts");
const src=fileURLToPath(new URL(".",import.meta.url)),root=path.resolve(src,"../.."),out=path.join(root,process.argv.includes("--release")?"public/practice/es/hotel":".qa-guided/hotel/pack");
await fs.mkdir(out,{recursive:true});
await build({entryPoints:[path.join(src,"entry.tsx")],outfile:path.join(out,"app.js"),bundle:true,minify:true,jsx:"automatic",target:"safari16",external:["./inter.woff2"],define:{"process.env.NODE_ENV":'"production"'}});
const assets={"desk.webp":"images/yo/voyage/do/conversation-hotel-checkin.webp","icon.png":"icon-192.png","yoppo.png":"companion/travel/companion-travel-teacher-ready.png","happy.png":"companion/travel/companion-travel-celebrating.png","inter.woff2":"fonts/inter.woff2"};
for(const l of lines)assets[l.id+".mp3"]=l.audioSrc.slice(1);
for(const [name,source] of Object.entries(assets))await fs.copyFile(path.join(root,"public",source),path.join(out,name));
await fs.copyFile(path.join(src,"index.html"),path.join(out,"index.html"));
await fs.writeFile(path.join(out,"manifest.webmanifest"),JSON.stringify({name:"YoPratiqo · En recepción",short_name:"En recepción",display:"standalone",start_url:"./index.html",scope:"./",icons:[{src:"./icon.png",sizes:"192x192",type:"image/png"}]}));
const files=["index.html","app.js","app.css","manifest.webmanifest",...Object.keys(assets)],hash=createHash("sha256");
for(const f of files)hash.update(f).update(await fs.readFile(path.join(out,f)));
const worker=await fs.readFile(path.join(root,"tools/italy-by-train/sw.js"),"utf8"),revision=hash.update(worker).digest("hex").slice(0,16);
await fs.writeFile(path.join(out,"sw.js"),"const PACK="+JSON.stringify(files)+",REVISION="+JSON.stringify(revision)+";\n"+worker);
await fs.writeFile(path.join(out,"pack.json"),JSON.stringify({files:[...files,"sw.js"],revision}));
console.log("Hotel pack",revision,files.length,"offline resources;",lines.length,"existing course recordings.");
