create or replace view public.teachers_public as
select
  id,
  name,
  discipline,
  category,
  rating,
  reviews,
  price_per_lesson,
  monthly_subscription,
  bio,
  image_url,
  availability,
  (location - 'private'::text) as location,
  is_verified,
  teaching_mode,
  languages,
  levels,
  created_at,
  updated_at,
  home_lesson_enabled,
  home_lesson_price,
  home_lesson_radius_km,
  home_lesson_min_duration,
  home_lesson_requires_confirmation,
  home_lesson_force_2h_over_20km,
  verification_level,
  identity_verified,
  diploma_verified,
  phone_verified,
  video_url,
  identity_status,
  diploma_url,
  country_code,
  timezone,
  currency,
  city,
  region,
  location_verification_status,
  location_verified_at,
  location_verification_method,
  cv_summary,
  cv_verification_status,
  intro_session_enabled,
  intro_session_duration_minutes,
  intro_session_price_cents,
  intro_session_discount_percent,
  user_id
from public.teachers t
where coalesce(is_public, true) = true
  and deactivated_at is null
  and deleted_at is null
  and id ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$';
