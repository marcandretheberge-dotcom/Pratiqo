import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { isGuidedStripeReturnOnlyChange } from "../helpers/guidedStripeReturnScope";
import { guidedBookingState, suggestTeacherRegion, teacherSetupStep, teacherSetupHref, guidedSetupSectionHref, isGuidedSetupComplete } from "../../lib/teachers/guidedSetup";
import { evaluateTeacherProfilePublishEligibility } from "../../lib/teachers/profilePublishEligibility";

assert.equal(guidedSetupSectionHref("availability"), "/teacher/schedule?setup=1");
assert.equal(guidedSetupSectionHref("pricing"), "/teacher/verification?setup=1&section=pricing");
const publication = evaluateTeacherProfilePublishEligibility({ id: "11111111-1111-4111-8111-111111111111", user_id: "22222222-2222-4222-8222-222222222222", name: "Teacher", bio: "A sufficient synthetic biography.", disciplineCount: 1, price_per_lesson: 45, availability: ["Lun Matin"], city: "Saint-Georges", region: "QC", country_code: "CA", is_public: true });
assert.equal(isGuidedSetupComplete("book", publication), true);
for (const state of ["request", "contact", "waitlist", "unknown", "not_public"]) assert.equal(isGuidedSetupComplete(state, publication), false);
assert.equal(isGuidedSetupComplete("book", { ...publication, status: "private_draft" }), false);
assert.equal(isGuidedSetupComplete("book", null), false);

assert.equal(teacherSetupStep("payments"), "payments");
assert.equal(teacherSetupStep("https://untrusted.invalid"), "course");
assert.equal(teacherSetupHref("availability"), "/teacher/schedule?setup=1");
assert.equal(guidedBookingState({ action: "book", hasSlot: true }, false), "not_public");
assert.equal(guidedBookingState(null, true), "unknown");
assert.equal(guidedBookingState({ action: "request", hasSlot: true }, true), "request");
assert.equal(guidedBookingState({ action: "contact", hasSlot: false }, true), "contact");
assert.equal(guidedBookingState({ action: "book", hasSlot: true }, true), "book");
assert.deepEqual(suggestTeacherRegion("Saint-Georges", {}), { region: "QC", country: "CA", timezone: "America/Toronto" });
assert.equal(suggestTeacherRegion("Saint-Georges", { timezone: "America/Vancouver" }).timezone, "America/Vancouver");
assert.deepEqual(suggestTeacherRegion("Unlisted city", {}), {});
assert.deepEqual(suggestTeacherRegion("Saint-Georges", { country: "FR" }), { country: "FR" });
const connect = readFileSync("app/api/stripe/connect/route.ts", "utf8");
const base = execFileSync("git", ["merge-base", "HEAD", "origin/main"], { encoding: "utf8" }).trim();
const original = execFileSync("git", ["show", `${base}:app/api/stripe/connect/route.ts`], { encoding: "utf8" });
assert.equal(isGuidedStripeReturnOnlyChange("app/api/stripe/connect/route.ts", original, connect), true);
assert.equal(isGuidedStripeReturnOnlyChange("app/api/stripe/connect/route.ts", original, connect + "\n// Other change"), false);
assert.equal(isGuidedStripeReturnOnlyChange("app/api/stripe/connect/route.ts", original, connect.replace("/teacher/setup-payments?setup=1&", "https://untrusted.invalid/?")), false);
assert.equal(isGuidedStripeReturnOnlyChange("app/api/stripe/webhook/route.ts", original, connect), false);
assert.match(connect, /searchParams.get\("flow"\) === "teacher-setup"/);
assert.match(connect, /:\s*"\/onboarding\?"/);
const payments = readFileSync("app/(app)/teacher/setup-payments/page.tsx", "utf8");
assert.ok(payments.indexOf('fetch("/api/stripe/connect"') < payments.indexOf('fetch("/api/teacher/setup-status"'));
assert.doesNotMatch(payments, /stripe.*===.*success/);
assert.match(payments, /inFlight.current/);
