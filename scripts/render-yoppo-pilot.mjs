function run(command,args,allowFailure=false) {
  const result=spawnSync(command,args,{encoding:"utf8",timeout:180000,maxBuffer:20*1024*1024});
  const entry={command,args,status:result.status,error:result.error?.message??null};commands.push(entry);
  fs.appendFileSync(path.join(out,"commands.log"),JSON.stringify(entry)+"\n"+(result.stdout??"")+(result.stderr??"")+"\n");
  if(result.error) throw result.error;
  if(!allowFailure) assert.equal(result.status,0,`${path.basename(command)} failed; see ${out}/commands.log`);
  return result;
}
