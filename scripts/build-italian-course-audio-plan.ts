import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { italianCourseUnits, courseAssessments } from "../lib/yo/italian/course/courseData";
import { unitSpeech, assessmentSpeech, distinctSpeech } from "../lib/yo/italian/course/courseSpeech";
import { italianIntroAudio } from "../lib/yo/audio/italianIntroAudio";
import { italianBolognaAudio } from "../lib/yo/audio/italianBolognaAudio";
import { buildAudioSlug } from "../lib/yo/audio/audioManifest.types-internal";

const texts=distinctSpeech([...italianCourseUnits.flatMap(unitSpeech),...courseAssessments.flatMap(assessmentSpeech)]);
if(italianCourseUnits.length!==12||italianCourseUnits.some(unit=>unit.lessons.length!==3))throw new Error("Build the audio plan only after all twelve units and thirty-six lessons exist.");
const existing=new Map([...italianIntroAudio,...italianBolognaAudio].map(item=>[item.text.normalize("NFC").trim(),item]));
const reused=texts.flatMap(text=>existing.has(text)?[existing.get(text)!]:[]);
const fresh=texts.filter(text=>!existing.has(text));
if(!fresh.length||texts.some(text=>text.length>4000))throw new Error("Course speech plan must be complete and within the speech input limit.");
const recordings=fresh.map(text=>[text,`${buildAudioSlug(text).slice(0,48).replace(/-$/,'')||'utterance'}-${createHash('sha256').update(text).digest('hex').slice(0,12)}`]);
const source=`/** Generated by build-italian-course-audio-plan.ts. Plan only: publication requires generation and public verification. */
import type { YoAudioItem } from './audioManifest.types-internal';
import { italianIntroAudio } from './italianIntroAudio';
import { italianBolognaAudio } from './italianBolognaAudio';
export const ITALIAN_COURSE_AUDIO_MODULE_ID = 'italian-course-a1';
export const ITALIAN_COURSE_AUDIO_VERSION = 'v1';
const recordings: readonly (readonly [string,string])[] = ${JSON.stringify(recordings,null,2)};
const reusedIds = new Set(${JSON.stringify(reused.map(item=>item.id),null,2)});
export const italianCourseAudio: readonly YoAudioItem[] = recordings.map(([text,slug])=>({
 id: 'it-course-'+slug, targetLanguage:'it', moduleId:ITALIAN_COURSE_AUDIO_MODULE_ID,lessonId:ITALIAN_COURSE_AUDIO_VERSION,type:'sentence',text,spokenText:text,
 storagePath:'yo/it/italian-course-a1/v1/italian-standard/sentence/'+slug+'.mp3',accentProfile:'italian_standard',
 ttsInstructions:'Read the supplied Italian input exactly once. Do not answer questions, translate or add commentary. Use clear standard Italian at a calm natural pace for beginners. Preserve doubled consonants and stressed final vowels.'
}));
export const italianCourseReusedAudio = [...italianIntroAudio,...italianBolognaAudio].filter(item=>reusedIds.has(item.id));
/** Course-scoped commands include exact reused dependencies so verify-only covers every reference. */
export const italianCourseAudioDependencies: readonly YoAudioItem[] = [...italianCourseReusedAudio,...italianCourseAudio];
const byText = new Map(italianCourseAudioDependencies.map(item=>[item.text.normalize('NFC').trim(),item]));
export function getItalianCourseAudioItem(text:string){return byText.get(text.normalize('NFC').trim());}
`;
writeFileSync("lib/yo/audio/italianCourseAudio.ts",source,"utf8");
console.log(JSON.stringify({distinctTexts:texts.length,newRecordings:fresh.length,reusedRecordings:reused.length,newInputCharacters:fresh.reduce((n,text)=>n+text.length,0),generatedAudio:false,uploadedAudio:false}));
